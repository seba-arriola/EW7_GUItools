connect SYS/change_on_install as SYSDBA
set echo on
spool logs\CreateDB.log
startup nomount pfile="init$(EW_ORACLE_SID).ora";
CREATE DATABASE $(EW_ORACLE_SID)
MAXINSTANCES 1
MAXLOGHISTORY 1
MAXLOGFILES 5
MAXLOGMEMBERS 3
MAXDATAFILES 100
DATAFILE '$(EW_SYSTEM_DIR)\system01.dbf' SIZE 250M REUSE AUTOEXTEND ON NEXT  10240K MAXSIZE UNLIMITED
EXTENT MANAGEMENT LOCAL
DEFAULT TEMPORARY TABLESPACE TEMP TEMPFILE '$(EW_ORACLE_BASE)\oradata\$(EW_ORACLE_SID)\temp01.dbf' SIZE 40M REUSE AUTOEXTEND ON NEXT  640K MAXSIZE UNLIMITED
UNDO TABLESPACE $(EW_ROLLBACK_TABLESPACE) DATAFILE '$(EW_UNDO_DIR)\undotbs01.dbf' SIZE 200M REUSE AUTOEXTEND ON NEXT  5120K MAXSIZE UNLIMITED
CHARACTER SET WE8MSWIN1252
NATIONAL CHARACTER SET AL16UTF16
LOGFILE GROUP 1 ('$(EW_ORACLE_LOG_DIR1)\redo01.log') SIZE 102400K,
GROUP 2 ('$(EW_ORACLE_LOG_DIR2)\redo02.log') SIZE 102400K,
GROUP 3 ('$(EW_ORACLE_LOG_DIR3)\redo03.log') SIZE 102400K;
spool off
exit;
