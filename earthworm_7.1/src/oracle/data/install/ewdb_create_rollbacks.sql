
connect SYS/change_on_install as SYSDBA
set echo on
spool logs\create_rollbacks.log

REM **** Creating two rollback segments ****************
CREATE PUBLIC ROLLBACK SEGMENT RB0 TABLESPACE $(EW_ROLLBACK_TABLESPACE)
STORAGE ( INITIAL 50K NEXT 50K MINEXTENTS 2 MAXEXTENTS UNLIMITED);
CREATE PUBLIC ROLLBACK SEGMENT RB1 TABLESPACE $(EW_ROLLBACK_TABLESPACE)
STORAGE ( INITIAL 50K NEXT 50K MINEXTENTS 2 MAXEXTENTS UNLIMITED);
ALTER ROLLBACK SEGMENT "RB0" ONLINE;
ALTER ROLLBACK SEGMENT "RB1" ONLINE;



spool off
exit;
